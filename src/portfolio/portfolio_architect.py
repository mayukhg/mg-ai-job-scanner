    def _write_requirements(self, project_dir: Path):
        """Creates TDD requirements with pytest."""
        content = [
            "pyyaml==6.0.1",
            "requests==2.31.0",
            "pytest==8.1.1",
            "pytest-mock==3.12.0"
        ]
        with open(project_dir / "requirements.txt", 'w', encoding='utf-8') as f:
            f.write("\n".join(content))

        # Also write pytest.ini configuration
        pytest_ini = [
            "[pytest]",
            "pythonpath = . src",
            "testpaths = tests",
            "python_files = test_*.py"
        ]
        with open(project_dir / "pytest.ini", 'w', encoding='utf-8') as f:
            f.write("\n".join(pytest_ini))

