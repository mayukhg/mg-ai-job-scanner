import logging
from pathlib import Path
from typing import List, Dict, Any
from ..analyzer.trending import TrendStorageManager

logger = logging.getLogger("portfolio.architect")

class AgentPortfolioArchitect:
    """
    Agent Portfolio Architect (Project Scaffolder) translates trending market technologies
    into structured, functional open-source proof-of-concept repositories on GitHub.
    It builds layouts, templates, README files, test suites, and actions configs.
    """
    def __init__(self, db_manager: TrendStorageManager, config: dict = None):
        self.db = db_manager
        self.config = config or {}
        self.base_dir = Path(self.config.get("portfolio", {}).get(
            "output_base_dir", "data/portfolio/scaffolds"
        ))
        
    def scaffold_trending_project(self, week_identifier: str) -> Dict[str, Any]:
        """
        Retrieves top trending skill sets, synthesizes a target project design,
        scaffolds a complete directory workspace, and logs it to SQLite.
        """
        logger.info(f"Initiating Agent Portfolio Scaffolding cycle for week: {week_identifier}...")
        
        # 1. Fetch top trending skills from relational storage
        with self.db._get_connection() as conn:
            cursor = conn.cursor()
            cursor.execute("SELECT topic_name FROM trending_topics ORDER BY created_at DESC LIMIT 2")
            rows = cursor.fetchall()
            
        tech_stack = [row[0] for row in rows] if rows else ["LangGraph State Sync", "SQLite Persistence"]
        
        # 2. Synthesize project nomenclature
        normalized_name = tech_stack[0].lower().strip().replace(" ", "-")
        project_name = f"{normalized_name}-proof-of-work"
        project_dir = self.base_dir / project_name
        
        logger.info(f"Targeting Tech Stack: {tech_stack}")
        logger.info(f"Generating physical open-source project workspace at: {project_dir}")
        
        # 3. Create directory structures
        project_dir.mkdir(parents=True, exist_ok=True)
        (project_dir / "src").mkdir(exist_ok=True)
        (project_dir / "tests").mkdir(exist_ok=True)
        (project_dir / ".github" / "workflows").mkdir(parents=True, exist_ok=True)
        
        # 4. Generate core code files
        self._write_readme(project_dir, project_name, tech_stack)
        self._write_main_code(project_dir, tech_stack)
        self._write_requirements(project_dir)
        self._write_tests(project_dir, project_name)
        self._write_ci_workflow(project_dir)
        
        # 5. Record to SQLite database catalog
        github_url = f"https://github.com/mayukhg/{project_name}"
        self.db.record_portfolio_project(
            project_name=project_name,
            tech_stack=tech_stack,
            local_path=str(project_dir),
            github_repo_url=github_url
        )
        
        logger.info(f"Portfolio Scaffold successfully generated and indexed inside SQLite: {github_url}")
        return {
            "project_name": project_name,
            "tech_stack": tech_stack,
            "local_path": str(project_dir),
            "github_repo_url": github_url
        }

    def _write_readme(self, project_dir: Path, name: str, tech_stack: List[str]):
        """Generates a premium README.md explaining the TDD proof-of-work project."""
        content = [
            f"# {name.replace('-', ' ').title()} — TDD Upskilling Lab",
            f"\n> **Proof-of-Expertise Challenge**: This repository is a Test-Driven Development (TDD) upskilling challenge.",
            f"\nCIE has generated this repository equipped with a robust and **failing** test suite. Your challenge is to complete the implementation stubs to make all test cases pass.",
            f"\n## 🛠️ Target Technology Stack",
            "".join([f"\n* **{tech}**" for tech in tech_stack]),
            f"\n## 🏗️ Architecture Blueprint",
            f"```",
            f"  ┌──────────────────────┐      ┌──────────────────────┐",
            f"  │  Candidate Source    │ ───► │  TDD Pytest Suite    │",
            f"  │  (main.py Stubs)     │ ◄─── │  (Failing by Design) │",
            f"  └──────────────────────┘      └──────────────────────┘",
            f"```",
            f"\n## 🚀 Getting Started",
            f"1. **Install environment and pytest**:",
            f"   ```bash",
            f"   pip install -r requirements.txt",
            f"   ```",
            f"2. **Run Pytest (TDD Mode)**:",
            f"   ```bash",
            f"   pytest",
            f"   ```",
            f"3. **Complete the Challenge**: Open `src/main.py` and implement the placeholder stubs until all unit and integration tests turn green!",
            f"\n*Auto-generated by Career Intelligence Engine (CIE) Portfolio Architect.*"
        ]
        with open(project_dir / "README.md", 'w', encoding='utf-8') as f:
            f.write("\n".join(content))

